def route_label(category, name):
    # 보고서는 노선번호만 적고 "급행" 여부는 구분 컬럼에 따로 적어서,
    # 기존 데이터(bus_route_timetable.json)의 "급행1번" 식 표기에 맞춘다.
    number = name.split("(")[0]
    return f"급행{number}" if category == "급행" else number


def main():
    routes = {}
    for category, name, am, noon, pm, avg in ROWS:
        label = route_label(category, name)
        origin_dest = name.split("(", 1)[1].rstrip(")")
        origin, _, dest = origin_dest.partition("~")
        routes[label] = {
            "category": category,
            "origin": origin,
            "dest": dest,
            "speedAmKmh": am,
            "speedNoonKmh": noon,
            "speedPmKmh": pm,
            "speedAvgKmh": avg,
        }

    print(f"노선 수: {len(routes)}")

    output = {
        "source": "2022년도 대전광역시 교통현황조사 및 분석, 제3장 2.버스 통행속도 (p.390-392)",
        "note": "DSRC-RSE 기반 실측 평균 통행속도(km/h), 2022년 10월 기준. 현재 노선 목록과 완전히 같지 않을 수 있음.",
        "categoryAverages": {
            k: {"speedAmKmh": v[0], "speedNoonKmh": v[1], "speedPmKmh": v[2], "speedAvgKmh": v[3]}
            for k, v in CATEGORY_AVERAGES.items()
        },
        "routes": routes,
    }

    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        json.dump(output, f, ensure_ascii=False, indent=2)

    print(f"저장: {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
